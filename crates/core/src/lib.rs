//! Расчётное ядро тайм-листа.
//!
//! Модуль не зависит от БД, сети и UI, поэтому его можно подключить к любой
//! другой системе (например, к CRM) как обычную библиотеку:
//!
//! * [`calc`] — формулы листов «Табель» и «Сводка» исходной Excel-книги;
//! * [`parser`] — разбор сообщений из группы Telegram («офис», «уход 17.30» …);
//! * [`automark`] — превращение сообщений и периодов отсутствия в отметки дня;
//! * [`calendar`] — рабочие/нерабочие дни и нормы времени.

pub mod automark;
pub mod calc;
pub mod calendar;
pub mod model;
pub mod parser;
pub mod timefmt;

